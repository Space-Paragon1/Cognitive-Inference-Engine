#!/usr/bin/env node
/**
 * Copies the design system into the extension. Chrome extensions can't import
 * from the app, so the popup and the blocked-tab overlay carry their own copies:
 *
 *   popup/popup.html   design/tokens.css inlined between the clr-tokens markers
 *   clr-tokens.js      the same tokens as a string for the overlay's shadow root
 *                      (:root becomes :host, so they never leak into the page)
 *   clr-icons.js       the Lucide icons the popup and overlay use, as SVG strings
 *   fonts/             Geist 400/500/600 and Geist Mono 500 for the popup
 *
 * Run from the repo root after `npm install` in frontend/:
 *   node plugins/browser-extension/scripts/sync-design.mjs
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const EXT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = join(EXT, "..", "..");
const MODULES = join(ROOT, "frontend", "node_modules");

const ICONS = [
  "settings",
  "shield-check",
  "external-link",
  "arrow-left",
  "timer",
  "wifi-off",
  "unplug",
  "target",
  "waves",
  "repeat",
  "battery-low",
  "leaf",
  "circle-dashed",
  "check",
];

const tokens = readFileSync(join(ROOT, "design", "tokens.css"), "utf8").trim();

// 1. Popup: inline the tokens.
const popupPath = join(EXT, "popup", "popup.html");
const popup = readFileSync(popupPath, "utf8");
const block = /\/\* clr-tokens:start \*\/[\s\S]*?\/\* clr-tokens:end \*\//;
if (!block.test(popup)) throw new Error("popup.html has no clr-tokens markers");
writeFileSync(popupPath, popup.replace(block, () => `/* clr-tokens:start */\n${tokens}\n/* clr-tokens:end */`));

// 2. Overlay: the same tokens, scoped to the shadow host.
const shadow = tokens.replace(/:root/g, ":host");
writeFileSync(
  join(EXT, "clr-tokens.js"),
  `/* Generated by scripts/sync-design.mjs from design/tokens.css. Do not edit. */\n` +
    `// clr-tokens:start\nconst CLR_TOKENS_CSS = ${JSON.stringify(shadow)};\n// clr-tokens:end\n`
);

// 3. Icons, from lucide-react's icon nodes.
const out = {};
for (const name of ICONS) {
  const iconFile = (n) => join(MODULES, "lucide-react", "dist", "esm", "icons", `${n}.mjs`);
  let mod = await import(pathToFileURL(iconFile(name)).href);
  // Some names are aliases (waves → waves-horizontal) that only re-export the default.
  const alias = readFileSync(iconFile(name), "utf8").match(/from '\.\/([\w-]+)\.mjs'/);
  if (!mod.__iconData && alias) mod = await import(pathToFileURL(iconFile(alias[1])).href);
  out[name] = mod.__iconData.node
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ")}/>`)
    .join("");
}
writeFileSync(
  join(EXT, "clr-icons.js"),
  `/* Generated by scripts/sync-design.mjs from lucide-react. Do not edit. */\n` +
    `const CLR_ICON_PATHS = ${JSON.stringify(out, null, 2)};\n\n` +
    `/** An inline Lucide icon: 24-unit grid, 2px stroke, currentColor. */\n` +
    `function clrIcon(name, size = 16) {\n` +
    `  return \`<svg xmlns="http://www.w3.org/2000/svg" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">\${CLR_ICON_PATHS[name] || ""}</svg>\`;\n` +
    `}\n`
);

// 4. Fonts for the popup.
mkdirSync(join(EXT, "fonts"), { recursive: true });
for (const w of [400, 500, 600]) {
  copyFileSync(join(MODULES, "@fontsource", "geist", "files", `geist-latin-${w}-normal.woff2`), join(EXT, "fonts", `geist-${w}.woff2`));
}
copyFileSync(join(MODULES, "@fontsource", "geist-mono", "files", "geist-mono-latin-500-normal.woff2"), join(EXT, "fonts", "geist-mono-500.woff2"));

console.log("Synced tokens, icons and fonts into", EXT);
